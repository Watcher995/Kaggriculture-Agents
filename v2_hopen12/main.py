"""Hybrid agent: our planner (base) for steps < SWITCH_A, 1st-place search (S1) from SWITCH_A on.
Optional: S1_UNTIL_DAY29_ONLY -> base until day 29, S1 on day 29.
Both agents live in the same process but in separate namespaces.
Generated by build_hybrid.py; constants are filled in below.
"""
import os, sys, importlib.util, types

SWITCH_STEP = 288   # first step handled by S1 (must be a dawn: multiple of 24)
def _find_here():
    cands = []
    f = globals().get('__file__')
    if f:
        cands.append(os.path.dirname(os.path.abspath(f)))
    cands += [p for p in reversed(sys.path) if p]
    cands += [os.getcwd(), '/kaggle_simulations/agent']
    for d in cands:
        if os.path.isfile(os.path.join(d, 'base_impl.py')) and os.path.isdir(os.path.join(d, 's1')):
            return os.path.abspath(d)
    raise FileNotFoundError('base_impl.py / s1 not found beside main.py')


_HERE = _find_here()
_BASE_PATH = os.path.join(_HERE, 'base_impl.py')
_S1_DIR = os.path.join(_HERE, 's1')

_base_ns = {'__file__': _BASE_PATH, '__name__': 'hy_base'}
exec(compile(open(_BASE_PATH).read(), _BASE_PATH, 'exec'), _base_ns)
_base_agent = _base_ns['agent']

_spec = importlib.util.spec_from_file_location('hy_s1_main', os.path.join(_S1_DIR, 'main.py'))
_s1 = importlib.util.module_from_spec(_spec)
_s1.__file__ = os.path.join(_S1_DIR, 'main.py')
_spec.loader.exec_module(_s1)


def agent(observation, configuration=None):
    step = int(observation['step'])
    if step < SWITCH_STEP:
        return _base_agent(observation, configuration)
    return _s1.agent(observation, configuration)
